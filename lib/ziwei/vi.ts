export const HOURS_VI = BRANCHES_VI.map((b, i) => {
  const start = (i * 2 + 23) % 24;
  const end = (start + 2) % 24;
  const pad = (n: number) => String(n).padStart(2, '0');
  return { branch: i, name: `Giờ ${b}`, range: `${pad(start)}:00–${pad(end)}:00` };
});

